import { defineConfig } from "vite-plus";

/**
 * `vp staged` (lint-staged) normally appends every staged path to the task
 * command. OS command lines are length-limited (Windows ~8k through cmd.exe;
 * POSIX far larger) and lint-staged's own arg-length guard ignores the
 * wrapper and quoting overhead, so a large commit can still overflow with
 * "The command line is too long". A task function lets us build the commands
 * ourselves, split into chunks sized to stay valid on every platform.
 *
 * lint-staged parses these strings back into argv in-process (string-argv),
 * so no shell ever sees the quoting; paths are wrapped in a quote character
 * they do not contain. This is platform-agnostic: no branch on process.platform.
 */
const MAX_COMMAND_CHARS = 6000;

function quotePath(file: string): string {
  const quote = file.includes('"') ? "'" : '"';
  return `${quote}${file}${quote}`;
}

function checkCommands(files: readonly string[]): string[] {
  const chunks: string[][] = [];
  let current: string[] = [];
  let length = 0;
  for (const file of files) {
    const quoted = quotePath(file);
    if (current.length > 0 && length + 1 + quoted.length > MAX_COMMAND_CHARS) {
      chunks.push(current);
      current = [];
      length = 0;
    }
    current.push(quoted);
    length += 1 + quoted.length;
  }
  if (current.length > 0) chunks.push(current);
  return chunks.map((chunk) => `vp check --fix ${chunk.join(" ")}`);
}

export default defineConfig({
  staged: {
    "*": checkCommands,
  },
  fmt: {
    // dist/ is generated by `npm run build`. The agent contract and its
    // harness-parity copies stay excluded: Oxfmt's blank-line insertion
    // would push AGENTS.md past azcodr's 120-line budget and desync the
    // byte-identical copies. Everything else, docs included, is formatted.
    ignorePatterns: [
      "dist/**",
      "AGENTS.md",
      "CLAUDE.md",
      "GEMINI.md",
      ".cursorrules",
      ".windsurfrules",
      ".github/copilot-instructions.md",
    ],
  },
  lint: {
    // dist/ is generated by `npm run build`; linting it only reports noise from
    // transpiled/minified output. Source, tests, scripts and `.agents/` stay in.
    ignorePatterns: ["dist/**"],
    jsPlugins: [{ name: "vite-plus", specifier: "vite-plus/oxlint-plugin" }],
    rules: { "vite-plus/prefer-vite-plus-imports": "error" },
    options: { typeAware: true, typeCheck: true },
  },
});
